"""Generate the mod-210 potential with smaller charges for four composite increments."""

import argparse
from collections import deque
from math import gcd

from travel_mod210_probe import P, clipped_hit


ALLOWANCES = {9: 315, 25: 525, 45: 315, 63: 315}
POTENTIAL_CAP = 1036


def rebalanced_potential():
    states = [(s, c) for c in range(0, P, 2) for s in range(P)]
    predecessors = {state: [] for state in states}
    for s, c in states:
        hit = clipped_hit(s, c)
        if hit is None:
            continue
        gap, clip = hit
        steps = [(clip, 0)]
        steps.extend((e, allowance) for e, allowance in ALLOWANCES.items() if gcd(e, P) == clip)
        for increment, allowance in steps:
            target = ((s + gap) % P, (c + increment - 1) % P)
            weight = 24 * gap - 11 * (increment - 1) - allowance
            predecessors[target].append(((s, c), weight))

    potential = dict.fromkeys(states, 0)
    pending = deque(states)
    enqueued = set(states)
    while pending:
        state = pending.popleft()
        enqueued.remove(state)
        for prior, weight in predecessors[state]:
            required = potential[state] + weight
            if required <= potential[prior]:
                continue
            assert required <= POTENTIAL_CAP, (prior, state, required)
            potential[prior] = required
            if prior not in enqueued:
                pending.append(prior)
                enqueued.add(prior)

    assert max(potential.values()) == POTENTIAL_CAP
    assert all(potential[state] + weight <= potential[prior]
               for state, incoming in predecessors.items() for prior, weight in incoming)
    return potential


def print_lean_data(potential):
    print("/- Generated by diagnostics/rebalanced_potential_probe.py --lean-data.")
    print("Each row packs 11 bits per value over its index period. -/")
    print("\nnamespace A166944Research\n")
    print("def rebalancedRows210 : Array (Nat × Nat) := #[")
    for c in range(0, P, 2):
        row = [potential[s, c] for s in range(P)]
        period = next(k for k in range(1, P + 1)
                      if P % k == 0 and all(row[s] == row[s % k] for s in range(P)))
        word = sum(value << (11 * s) for s, value in enumerate(row[:period]))
        print(f"  ({period}, {word}),")
    print("]\n\nend A166944Research")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean-data", action="store_true")
    args = parser.parse_args()
    values = rebalanced_potential()
    if args.lean_data:
        print_lean_data(values)
    else:
        print(f"Checked {len(values)} states with maximum potential {max(values.values())}.")
