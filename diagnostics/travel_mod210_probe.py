"""Compute the clipped residue tables and the separating-event charges."""

from math import gcd
from sys import argv

from travel_residue_probe import increment_at, odd_prime_divisors, travel_probe


P = 210


def clipped_hit(index, horizon):
    for gap in range(1, P + 1):
        hit = index + gap
        increment = gcd(P, increment_at(hit, horizon))
        if increment > 1:
            return gap, increment
    return None


def residue_tables():
    table = {(index, 0): (0, 0) for index in range(P)}
    for horizon in range(P - 2, 0, -2):
        for index in range(P):
            hit = clipped_hit(index, horizon)
            if hit is None:
                table[index, horizon] = (0, 0)
                continue
            gap, increment = hit
            growth = increment - 1
            assert gap <= 14 and horizon + growth <= P
            cap, potential = table[(index + gap) % P, (horizon + growth) % P]
            excess = max(0, 24 * gap - growth)
            table[index, horizon] = (excess + cap, max(0, excess + potential - 2 * growth))
    assert max(cap for cap, _ in table.values()) == table[23, 110][0] == 1316
    assert max(potential for _, potential in table.values()) == 1260
    return table


def print_lean_data(table):
    print("/- Generated by diagnostics/travel_mod210_probe.py --lean-data.")
    print("Each row is (period, packed values). Each entry uses 11 bits for")
    print("the excess cap followed by 11 bits for the potential. -/")
    print("\nnamespace A166944Research\n")
    print("def residueRows210 : Array (Nat × Nat) := #[")
    for horizon in range(0, P, 2):
        row = [table[index, horizon] for index in range(P)]
        period = next(d for d in range(1, P + 1)
                      if P % d == 0 and all(row[i] == row[i % d] for i in range(P)))
        word = sum((cap + 2048 * potential) << (22 * i)
                   for i, (cap, potential) in enumerate(row[:period]))
        print(f"  ({period}, {word}),")
    print("]\n\nend A166944Research")


def separator_summary(record, table):
    finish, hits, _ = travel_probe(record)
    index, horizon = record + 2, 2 * record - 2
    _, start_potential = table[index % P, horizon % P]
    seen = set()
    excess_total = charge = separators = short_charge = reuse_charge = 0

    for hit in hits:
        gap = hit - index
        increment = increment_at(hit, horizon)
        growth = increment - 1
        factors = list(odd_prime_divisors(increment))
        reused = factors == [increment] and increment in seen
        excess = max(0, 24 * gap - growth) if gap <= 10 or reused else 0
        updated = horizon + growth
        cap, potential = table[index % P, horizon % P]
        next_cap, next_potential = table[hit % P, updated % P]
        balance = excess + next_potential - potential - 2 * growth
        if P % increment == 0:
            assert excess + next_cap <= cap and balance <= 0
        else:
            separators += 1
            charge += max(0, balance)
            if gap <= 10:
                short_charge += max(0, balance)
            elif reused:
                reuse_charge += max(0, balance)
        excess_total += excess
        seen.update(factors)
        index, horizon = hit, updated

    assert horizon == finish
    growth_total = horizon - (2 * record - 2)
    _, end_potential = table[index % P, horizon % P]
    assert excess_total + end_potential <= 2 * growth_total + start_potential + charge
    return growth_total, excess_total, separators, charge, short_charge, reuse_charge


if __name__ == "__main__":
    table = residue_tables()
    if argv[1:] == ["--lean-data"]:
        print_lean_data(table)
        raise SystemExit(0)
    print(f"{len(table)} states, excess cap 1316, potential cap 1260")
    for label, record in (("certified", 22_933_441), ("actual start", 45_895_573),
                          ("synthetic", 23_613_589), ("synthetic", 23_619_049)):
        growth, excess, separators, charge, short, reuse = separator_summary(record, table)
        print(f"{label:12} {record=:9} {growth=:6} {excess=:6} {separators=:3} "
              f"{charge=:6} {short=:5} {reuse=:6}")
