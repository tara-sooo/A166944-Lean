#!/usr/bin/env python3
"""Generate the exact LOW7 22050-residue-state potential used by
A166944/Low7WheelData.lean.  The Lean theorem independently checks each edge.

Usage: python3 research/low7_wheel_generate.py > /tmp/Low7WheelData.lean
"""
from math import gcd

P = 105
L = 2 * P
N = P * L

def first_hit(t, c):
    for gap in range(1, 15):
        n = t + gap
        # Odd n-2 and c-1 are represented by positive numbers mod 210.
        x = n if n % 2 == 0 else n + 208
        y = c + 209 if n % 2 == 0 else c + 1
        d = gcd(gcd(x, 210), gcd(y, 210))
        assert d in (1, 3, 5, 7, 15, 21, 35, 105)
        if d > 1:
            return gap, d
    return None

def potentials():
    nxt = [-1] * N
    gap = [0] * N
    delta = [0] * N
    for h in range(P):
        for t in range(L):
            i = h * L + t
            hit = first_hit(t, 2 * h)
            if hit is not None:
                g, d = hit
                gap[i], delta[i] = g, d - 1
                nxt[i] = (((2*h + d - 1) % L) // 2) * L + ((t + g) % L)

    status = bytearray(N)
    elapsed, growth, count = [0]*N, [0]*N, [0]*N
    for root in range(N):
        if status[root]:
            continue
        stack = []
        u = root
        while u != -1 and status[u] == 0:
            stack.append(u)
            status[u] = 1
            u = nxt[u]
        if u >= 0 and status[u] == 1:
            raise AssertionError(("directed cycle", root, u))
        while stack:
            v = stack.pop()
            w = nxt[v]
            elapsed[v] = gap[v] + (elapsed[w] if w >= 0 else 0)
            growth[v] = delta[v] + (growth[w] if w >= 0 else 0)
            count[v] = (count[w] + 1 if w >= 0 else 0)
            status[v] = 2
    assert all(v == 2 for v in status)
    assert max(elapsed) == 56 and max(growth) == 106
    assert max(count) == 9
    return elapsed, growth

def main():
    elapsed, growth = potentials()
    print("/- Generated by research/low7_wheel_generate.py. -/")
    print("namespace A166944Research")
    print("def low7BudgetRows : Array Nat := #[")
    for h in range(P):
        bits = sum((elapsed[h*L+t]+256*growth[h*L+t]) << (16*t)
                   for t in range(L))
        print("  " + str(bits) + ("," if h < P-1 else ""))
    print("]")
    print("end A166944Research")

if __name__ == "__main__":
    main()
